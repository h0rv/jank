#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
ZIG="${ZIG:-zig}"
JANK="${JANK:-jank}"
RUNTIME="${JANK_RUNTIME_DIR:-/opt/homebrew/opt/jank/lib/jank/0.1}"
OUT="$ROOT/artifacts/jank-zig-cpp"
mkdir -p "$OUT"
"$ZIG" build -Doptimize=ReleaseSafe
VERSION="$("$JANK" print-binary-version)"
(
  cd jank
  "$JANK" --module-path src -L "$ROOT/zig-out/lib" -l:spike \
    --output-target cpp compile-module spike.core
  JANK_PRINT_CODEGEN=1 "$JANK" --module-path src -L "$ROOT/zig-out/lib" \
    -l:spike compile spike.core --name jank-print-codegen >"$OUT/generated.log" 2>&1
)
# jank prints its generated launcher after this marker. Do not extract JIT code,
# which can contain addresses meaningful only inside the compiler process.
awk '/\/\* DO NOT MODIFY: Autogenerated by jank\. \*\// {emit=1} emit' \
  "$OUT/generated.log" >"$OUT/main.cpp"
test -s "$OUT/main.cpp"
cpp_flags=()
runtime_libs=("$RUNTIME/lib/libc++.dylib" "$RUNTIME/lib/libunwind.dylib"
  "$RUNTIME/lib/clang/23/lib/darwin/libclang_rt.osx.a")
if [[ $(uname -s) == Linux ]]; then
  CXX="${CXX:-g++-14}"
  cpp_include="$("$CXX" -print-file-name=libstdc++.so)"
  cpp_include="$(dirname "$cpp_include")/../../../../include"
  cpp_flags=(-nostdinc++ -I "$cpp_include/c++/14"
    -I "$cpp_include/$("$CXX" -dumpmachine)/c++/14"
    -I "$cpp_include/c++/14/backward")
  runtime_libs=("-L$(dirname "$("$CXX" -print-libgcc-file-name)")"
    "$("$CXX" -print-file-name=libstdc++.so)"
    "$("$CXX" -print-file-name=libgcc_s.so)")
fi
"$ZIG" c++ -std=c++20 -O2 -fPIC -fwrapv -femulated-tls \
  "${cpp_flags[@]}" \
  -DGC_THREADS -DPOINTER_MASK=0x0000FFFFFFFFFFFF \
  -DIMMER_HAS_LIBGC=1 -DIMMER_TAGGED_NODE=0 -DBOOST_MP_STANDALONE=1 \
  -DFOLLY_HAVE_JEMALLOC=0 -DFOLLY_HAVE_TCMALLOC=0 \
  -DFOLLY_ASSUME_NO_JEMALLOC=1 -DFOLLY_ASSUME_NO_TCMALLOC=1 \
  -DJANK_VERSION='"jank-0.1-alpha"' -I "$RUNTIME/include" \
  -Wno-deprecated-literal-operator -Wno-return-type-c-linkage \
  -c "jank/target/_cache/$VERSION/spike/core.cpp" -o "$OUT/core.o"
# Use the installed runtime's C++ standard library rather than Zig's libc++.
"$ZIG" c++ -std=c++20 -O2 -femulated-tls -nostdlib++ \
  "${cpp_flags[@]}" \
  "$OUT/main.cpp" "$OUT/core.o" zig-out/lib/libspike.a \
  "$RUNTIME/lib/libjank-static-runtime.a" \
  "${runtime_libs[@]}" \
  "-Wl,-rpath,$RUNTIME/lib" -o "$OUT/jank-zig"
(cd /tmp && "$OUT/jank-zig") | tee "$OUT/execution.log"
grep -Fxq 'jank -> Zig: scalar and wide result checks passed' "$OUT/execution.log"
grep -Fxq 'jank -> Zig: borrowed-buffer checks passed' "$OUT/execution.log"
