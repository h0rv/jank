#!/usr/bin/env bash
# AI-assisted blocker probe; run inside the documented Ubuntu 24.04 container.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
APP="${JANK_ZIG_APP:-$ROOT}"
export JANK_ZIG_APP="$APP"
SOURCE="$(cd ../.. && pwd)/compiler+runtime"
SDK="${EMSDK:-$ROOT/.tools/gc-wasm/emsdk}"
BITS="${WASM_BITS:-64}"
case "$BITS" in
  32)
    memory_flags=(); builder_flags=()
    llvm_dependency_flags=(-Dzstd_LIBRARY=/usr/lib/x86_64-linux-gnu/libzstd.so
      -Dzstd_INCLUDE_DIR=/usr/include)
    ;;
  64) memory_flags=(-sMEMORY64=1); builder_flags=(--wasm64); llvm_dependency_flags=() ;;
  *) echo "WASM_BITS must be 32 or 64" >&2; exit 2 ;;
esac
BUILD="$ROOT/artifacts/build-wasm$BITS"
HEADERS="$ROOT/.tools/wasm$BITS-headers"
SPIKE="$ROOT/artifacts/wasm$BITS-spike"
export LANG=C.UTF-8 LC_ALL=C.UTF-8
export TMPDIR="$ROOT/artifacts/tmp" XDG_CACHE_HOME="$ROOT/.tools/host-cache"
mkdir -p "$TMPDIR" "$XDG_CACHE_HOME" artifacts/logs
export PATH="$SDK/upstream/emscripten:$SDK/upstream/bin:$PATH"
export EM_CONFIG="$SDK/.emscripten"
run() {
  local name=$1 status=0 start=$SECONDS
  shift
  "$@" > "artifacts/logs/wasm$BITS-$name.log" 2>&1 || status=$?
  printf '%s: exit=%s elapsed=%ss\n' "$name" "$status" "$((SECONDS-start))" |
    tee "artifacts/logs/wasm$BITS-$name.result"
  tail -n 20 "artifacts/logs/wasm$BITS-$name.log"
  return "$status"
}
generate_spike() {
  local host="$ROOT/artifacts/build-host/jank"
  export JANK_RUNTIME_DIR="$ROOT/artifacts/host-resources"
  mkdir -p "$SPIKE"
  (
    cd "$APP/jank" || exit
    "$host" --module-path src -L "$ROOT/zig-out/lib" -l:spike \
      --output-target cpp compile-module spike.core || exit
    JANK_PRINT_CODEGEN=1 "$host" --module-path src -L "$ROOT/zig-out/lib" -l:spike \
      compile spike.core --name "wasm$BITS-launcher" >"$SPIKE/generated.log" 2>&1
  ) || return
  awk '/\/\* DO NOT MODIFY: Autogenerated by jank\. \*\// {emit=1} emit' \
    "$SPIKE/generated.log" >"$SPIKE/main.cpp" || return
  test -s "$SPIKE/main.cpp" || { echo "Missing generated launcher" >&2; return 1; }
  "$host" print-binary-version >"$SPIKE/host-version"
}
generate_assertion() {
  local host="$ROOT/artifacts/build-host/jank"
  export JANK_RUNTIME_DIR="$ROOT/artifacts/host-resources"
  (
    cd jank || exit
    "$host" --module-path "$ROOT/wasm-probe" --output-target cpp \
      compile-module startup-assertion || exit
    JANK_PRINT_CODEGEN=1 "$host" --module-path "$ROOT/wasm-probe" \
      compile startup-assertion --name startup-assertion-launcher >"$SPIKE/assertion-generated.log" 2>&1
  ) || return
  awk '/\/\* DO NOT MODIFY: Autogenerated by jank\. \*\// {emit=1} emit' \
    "$SPIKE/assertion-generated.log" >"$SPIKE/assertion-main.cpp"
  test -s "$SPIKE/assertion-main.cpp"
}
case "${1:-configure}" in
  deps)
    run deps "$SDK/upstream/emscripten/embuilder" build zlib boost_headers "${builder_flags[@]}"
    mkdir -p "$HEADERS"
    for header in boost zlib.h zconf.h; do
      ln -sfn "$SDK/upstream/emscripten/cache/sysroot/include/$header" "$HEADERS/$header"
    done
    ;;
  configure)
    run configure emcmake cmake -S "$SOURCE" -B "$BUILD" -GNinja \
      -DCMAKE_BUILD_TYPE=Release -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
      -DCMAKE_DISABLE_PRECOMPILE_HEADERS=ON \
      "-DCMAKE_C_FLAGS=${memory_flags[*]} -fwasm-exceptions" \
      "-DCMAKE_CXX_FLAGS=${memory_flags[*]} -fwasm-exceptions" \
      "-DCMAKE_EXE_LINKER_FLAGS=${memory_flags[*]} -fwasm-exceptions" \
      -DCMAKE_FIND_ROOT_PATH_MODE_PACKAGE=BOTH \
      -DCMAKE_FIND_PACKAGE_PREFER_CONFIG=ON \
      -Dllvm_dir=/usr/lib/llvm-23 -Dclang_dir=/usr/lib/llvm-23 \
      -Dzstd_DIR=/usr/lib/x86_64-linux-gnu/cmake/zstd \
      "${llvm_dependency_flags[@]}" \
      -Djank_cross_compile=ON -Djank_emulated_tls=OFF -Denable_threads=OFF \
      "-DZLIB_LIBRARY=$SDK/upstream/emscripten/cache/sysroot/lib/wasm$BITS-emscripten/libz.a" \
      "-DZLIB_INCLUDE_DIR=$HEADERS" "-DBoost_INCLUDE_DIR=$HEADERS" \
      "-Djank_host_compiler=$ROOT/artifacts/build-host/jank-phase-1" \
      "-Djank_resource_dir=$ROOT/artifacts/host-resources" \
      -Djank_install_local_clang=OFF
    ;;
  build)
    run build cmake --build "$BUILD" -j "${JOBS:-6}" \
      --target jank_standalone_static_lib_phase_2 -- -k 0
    ;;
  spike)
    run spike-generate generate_spike
    run spike-zig "$ROOT/.tools/zig-x86_64-linux-0.17.1/zig" build-obj native.zig \
      -target "wasm$BITS-freestanding" -O ReleaseSafe "-femit-bin=$SPIKE/zig.o" \
      --cache-dir "$ROOT/.zig-cache" --global-cache-dir "$ROOT/.zig-cache/global"
    run spike-compile python3 - "$ROOT" "$BITS" <<'PY'
import json, pathlib, shlex, subprocess, sys
root = pathlib.Path(sys.argv[1])
out = root / f'artifacts/wasm{sys.argv[2]}-spike'
database = json.loads((root / f'artifacts/build-wasm{sys.argv[2]}/compile_commands.json').read_text())
entry = next(x for x in database if x['file'].endswith('/clojure/core.cpp'))
args = iter(shlex.split(entry['command']))
flags = [next(args)]
for arg in args:
    if arg in ('-o', '-MF', '-MT', '-MQ'):
        next(args)
    elif arg not in ('-c', '-MD', '-MMD', entry['file']):
        flags.append(arg)
version = (out / 'host-version').read_text().strip()
sources = [root / f'jank/target/_cache/{version}/spike/core.cpp', out / 'main.cpp',
           root / 'wasm-probe/runtime-smoke.cpp']
for source, name in zip(sources, ['core', 'main', 'runtime-smoke']):
    command = flags + ['-c', str(source), '-o', str(out / f'{name}.o')]
    print(shlex.join(command), flush=True)
    subprocess.run(command, cwd=entry['directory'], check=True)
PY
    run runtime-smoke-link em++ "${memory_flags[@]}" -fwasm-exceptions -O2 \
      "$SPIKE/runtime-smoke.o" "$BUILD/libjank-static-runtime.a" \
      -Wl,--error-limit=0 -o "$SPIKE/runtime-smoke.js"
    run runtime-smoke-run "$ROOT/.tools/node-v26.13.1-linux-x64/bin/node" "$SPIKE/runtime-smoke.js"
    grep -Fxq "wasm$BITS runtime: exception dispatch and unsupported capabilities passed" \
      "artifacts/logs/wasm$BITS-runtime-smoke-run.log"
    run spike-link em++ "${memory_flags[@]}" -fwasm-exceptions -O2 \
      "$SPIKE/main.o" "$SPIKE/core.o" "$SPIKE/zig.o" \
      "$BUILD/libjank-static-runtime.a" -Wl,--error-limit=0 -o "$SPIKE/spike.js"
    run spike-run "$ROOT/.tools/node-v26.13.1-linux-x64/bin/node" "$SPIKE/spike.js"
    grep -Fxq 'jank -> Zig: scalar and wide result checks passed' "artifacts/logs/wasm$BITS-spike-run.log"
    grep -Fxq 'jank -> Zig: borrowed-buffer checks passed' "artifacts/logs/wasm$BITS-spike-run.log"
    ;;
  startup-safepoints|startup-spill)
    variant="$1"
    iterations="${SAFEPOINT_ITERATIONS:-20}"
    if ! [[ "$iterations" =~ ^[0-9]+$ ]] || ((10#$iterations < 1 || 10#$iterations > 10000)); then
      echo 'SAFEPOINT_ITERATIONS must be an integer in [1, 10000]' >&2
      exit 2
    fi
    run "$variant-generate" generate_spike
    run "$variant-compile" python3 - "$ROOT" "$variant" "$BITS" <<'PY'
import json, os, pathlib, shlex, subprocess, sys
root = pathlib.Path(sys.argv[1])
bits = sys.argv[3]
out = root / f'artifacts/wasm{bits}-spike'
app = pathlib.Path(os.environ['JANK_ZIG_APP'])
build = root / f'artifacts/build-wasm{bits}'
variant = sys.argv[2]
database = json.loads((build / 'compile_commands.json').read_text())
entry = next(x for x in database if x['file'].endswith('/src/cpp/jank/runtime/context.cpp'))
args = iter(shlex.split(entry['command']))
flags = [next(args)]
for arg in args:
    if arg in ('-o', '-MF', '-MT', '-MQ'):
        next(args)
    elif arg not in ('-c', '-MD', '-MMD', entry['file']):
        flags.append(arg)
version = (out / 'host-version').read_text().strip()
objects = []
sources = [(out / 'main.cpp', 'main', ['-Dmain=jank_spike_main']),
           (app / f'jank/target/_cache/{version}/spike/core.cpp', 'core', []),
           (root / 'wasm-probe/startup-driver.cpp', 'driver', ['-DJANK_STARTUP_SPIKE_ONLY'])]
for source, label, extra in sources:
    obj = out / f'{variant}-{label}.o'
    subprocess.run(flags + ['-O2', '-g', *extra, '-c', str(source), '-o', str(obj)],
                   cwd=entry['directory'], check=True)
    objects.append(str(obj))
subprocess.run([str(root / '.tools/zig-x86_64-linux-0.17.1/zig'), 'build-obj',
                str(app / 'native.zig'), '-target', f'wasm{bits}-freestanding', '-O', 'ReleaseSafe',
                f'-femit-bin={out / (variant + "-zig.o")}',
                '--cache-dir', str(root / '.zig-cache'),
                '--global-cache-dir', str(root / '.zig-cache/global')], check=True)
subprocess.run([flags[0], '-O2', '-g', '--profiling-funcs',
                *(['-sMEMORY64=1'] if bits == '64' else []), '-fwasm-exceptions',
                '-sALLOW_MEMORY_GROWTH=1',
                *(['-sSTACK_SIZE=4194304'] if variant == 'startup-spill' else []),
                *(['-sEXIT_RUNTIME=1'] if os.environ.get('JANK_ZIG_APP_MODE') == '1' else []),
                *objects, str(out / (variant + '-zig.o')),
                str(build / 'libjank-static-runtime.a'), '-Wl,--error-limit=0',
                '-o', str(out / (variant + '.js'))], check=True)
PY
    if [[ "$variant" == startup-spill ]]; then
      run startup-spill python3 "$ROOT/wasm-probe/startup-spill.py" "$ROOT" "$iterations" "$BITS"
      exit 0
    fi
    failed=0
    : > artifacts/logs/wasm64-startup-safepoints.results
    for strategy in no-gc static-roots safepoint safepoint-churn; do
      status=0
      run "startup-safepoints-$strategy" "$ROOT/.tools/node-v26.13.1-linux-x64/bin/node" \
        "$SPIKE/startup-safepoints.js" "$strategy" "$iterations" || status=$?
      scalar=missing buffer=missing
      log="artifacts/logs/wasm64-startup-safepoints-$strategy.log"
      grep -Fxq 'jank -> Zig: scalar and wide result checks passed' "$log" && scalar=present
      grep -Fxq 'jank -> Zig: borrowed-buffer checks passed' "$log" && buffer=present
      printf '%s: exit=%s scalar=%s buffer=%s\n' "$strategy" "$status" "$scalar" "$buffer" |
        tee -a artifacts/logs/wasm64-startup-safepoints.results
      if [[ "$strategy" == safepoint* ]]; then
        python3 "$ROOT/wasm-probe/startup-safepoints-check.py" "$log" "$strategy" "$iterations" "$status" |
          tee -a artifacts/logs/wasm64-startup-safepoints.results || failed=1
      fi
      if [[ "$strategy" != static-roots ]] &&
          { [[ "$status" != 0 ]] || [[ "$scalar" != present ]] || [[ "$buffer" != present ]]; }; then
        failed=1
      fi
    done
    exit "$failed"
    ;;
  gc-roots)
    run gc-roots python3 "$ROOT/wasm-probe/gc-roots-matrix.py" "$ROOT"
    ;;
  gc-lifetime)
    run gc-lifetime python3 "$ROOT/wasm-probe/gc-roots-matrix.py" "$ROOT" "$BITS"
    ;;
  startup-roots)
    run startup-roots-compile python3 - "$ROOT" "$BITS" "${memory_flags[@]}" <<'PY'
import json, pathlib, shlex, subprocess, sys
root = pathlib.Path(sys.argv[1])
target = f'wasm{sys.argv[2]}'
out = root / f'artifacts/{target}-spike'
out.mkdir(exist_ok=True)
for name in ['host', target]:
    build = root / f'artifacts/build-{name}'
    database = json.loads((build / 'compile_commands.json').read_text())
    entry = next(x for x in database if x['file'].endswith('/src/cpp/jank/runtime/context.cpp'))
    args = iter(shlex.split(entry['command']))
    flags = [next(args)]
    for arg in args:
        if arg in ('-o', '-MF', '-MT', '-MQ'):
            next(args)
        elif arg not in ('-c', '-MD', '-MMD', entry['file']):
            flags.append(arg)
    obj = out / f'startup-roots-{name}.o'
    subprocess.run(flags + ['-c', str(root / 'wasm-probe/startup-roots.cpp'), '-o', str(obj)],
                   cwd=entry['directory'], check=True)
    link = [flags[0], str(obj), str(build / 'libjank-static-runtime.a')]
    if name == target:
        link += sys.argv[3:] + ['-fwasm-exceptions', '-sASSERTIONS=2', '-sSAFE_HEAP=1', '-g',
                 '-sALLOW_MEMORY_GROWTH=1']
        exe = out / f'startup-roots-{name}.js'
    else:
        link += ['-lz', '-ldl', '-pthread']
        exe = out / f'startup-roots-{name}'
    subprocess.run(link + ['-o', str(exe)], check=True)
PY
    for target in host "wasm$BITS"; do
      for strategy in default registered; do
        status=0
        if [[ "$target" == host ]]; then
          run "startup-roots-$target-$strategy" "$SPIKE/startup-roots-host" "$strategy" || status=$?
        else
          run "startup-roots-$target-$strategy" "$ROOT/.tools/node-v26.13.1-linux-x64/bin/node" \
            "$SPIKE/startup-roots-wasm$BITS.js" "$strategy" || status=$?
        fi
        if [[ "$target:$strategy" == "wasm$BITS:default" ]]; then
          test "$status" -eq 1
        else
          test "$status" -eq 0
        fi
      done
    done
    ;;
  startup-trace)
    run startup-assertion-generate generate_assertion
    run startup-trace-compile python3 - "$ROOT" "$BITS" "${memory_flags[@]}" <<'PY'
import json, os, pathlib, shlex, shutil, subprocess, sys
root = pathlib.Path(sys.argv[1])
target = f'wasm{sys.argv[2]}'
out = root / f'artifacts/{target}-spike'
source = root.parent.parent / 'compiler+runtime/src/cpp/jank/runtime/context.cpp'
shutil.copyfile(source, out / 'context-startup.cpp')
subprocess.run(['git', 'apply', str(root / 'wasm-probe/startup-context.patch')], cwd=out,
               env={**os.environ, 'GIT_CEILING_DIRECTORIES': str(out.parent)}, check=True)
version = (out / 'host-version').read_text().strip()
for name in ['host', target]:
    build = root / f'artifacts/build-{name}'
    database = json.loads((build / 'compile_commands.json').read_text())
    entry = next(x for x in database if x['file'].endswith('/src/cpp/jank/runtime/context.cpp'))
    args = iter(shlex.split(entry['command']))
    flags = [next(args)]
    for arg in args:
        if arg in ('-o', '-MF', '-MT', '-MQ'):
            next(args)
        elif arg not in ('-c', '-MD', '-MMD', entry['file']):
            flags.append(arg)
    objects = []
    sources = [(out / 'context-startup.cpp', 'context'), (out / 'main.cpp', 'main'),
               (root / f'jank/target/_cache/{version}/spike/core.cpp', 'core'),
               (out / 'assertion-main.cpp', 'assertion-main'),
               (root / f'jank/target/_cache/{version}/startup_assertion.cpp', 'assertion-core'),
               (root / 'wasm-probe/startup-driver.cpp', 'driver')]
    for src, label in sources:
        obj = out / f'startup-trace-{name}-{label}.o'
        extra = ['-Dmain=jank_spike_main'] if label == 'main' else (
            ['-Dmain=jank_assertion_main'] if label == 'assertion-main' else [])
        compile_flags = [flags[0], '-std=gnu++20'] if label.endswith('main') and name == 'host' else flags
        subprocess.run(compile_flags + extra + ['-c', str(src), '-o', str(obj)],
                       cwd=entry['directory'], check=True)
        objects.append(str(obj))
    if name == target:
        zig = out / 'zig.o'
        link_flags = sys.argv[3:] + ['-fwasm-exceptions', '-sASSERTIONS=2', '-sSAFE_HEAP=1',
                      '-sALLOW_MEMORY_GROWTH=1', '-g']
        exe = out / f'startup-trace-{target}.js'
    else:
        zig = out / 'startup-trace-native-zig.o'
        subprocess.run([str(root / '.tools/zig-x86_64-linux-0.17.1/zig'), 'build-obj',
                        str(root / 'native.zig'), '-O', 'ReleaseSafe', f'-femit-bin={zig}',
                        '--cache-dir', str(root / '.zig-cache'),
                        '--global-cache-dir', str(root / '.zig-cache/global')], check=True)
        link_flags = ['-lz', '-ldl', '-pthread']
        exe = out / 'startup-trace-host'
    subprocess.run([flags[0], *objects, str(zig), str(build / 'libjank-static-runtime.a'),
                    *link_flags, '-o', str(exe)], check=True)
PY
    run startup-trace-host "$SPIKE/startup-trace-host"
    run startup-assertion-host "$SPIKE/startup-trace-host" default assertion
    run "startup-assertion-wasm$BITS" "$ROOT/.tools/node-v26.13.1-linux-x64/bin/node" \
      "$SPIKE/startup-trace-wasm$BITS.js" no-gc assertion
    grep -Fq 'startup diagnostic assertion' "artifacts/logs/wasm$BITS-startup-assertion-host.log"
    grep -Fq 'startup diagnostic assertion' "artifacts/logs/wasm$BITS-startup-assertion-wasm$BITS.log"
    for strategy in default no-gc static-roots; do
      run "startup-trace-wasm$BITS-$strategy" "$ROOT/.tools/node-v26.13.1-linux-x64/bin/node" \
        "$SPIKE/startup-trace-wasm$BITS.js" "$strategy" || true
    done
    echo 'Diagnostic only: inspect logs; no-gc markers do not establish runtime correctness.'
    for control in host "wasm$BITS-no-gc"; do
      grep -Fxq 'jank -> Zig: scalar and wide result checks passed' "artifacts/logs/wasm$BITS-startup-trace-$control.log"
      grep -Fxq 'jank -> Zig: borrowed-buffer checks passed' "artifacts/logs/wasm$BITS-startup-trace-$control.log"
    done
    grep -Fxq 'jank -> Zig: scalar and wide result checks passed' "artifacts/logs/wasm$BITS-startup-trace-wasm$BITS-default.log"
    grep -Fxq 'jank -> Zig: borrowed-buffer checks passed' "artifacts/logs/wasm$BITS-startup-trace-wasm$BITS-default.log"
    ;;
  *) echo "Usage: $0 {deps|configure|build|spike|gc-roots|gc-lifetime|startup-roots|startup-trace|startup-safepoints|startup-spill}" >&2; exit 2 ;;
esac
